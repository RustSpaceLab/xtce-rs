//! `xtce wireshark` — compile an XTCE definition into a Wireshark Lua dissector (`.lua`).
//!
//! During spacecraft bench integration (FlatSat / EGSE), engineers inspect live UDP telemetry
//! or recorded `.pcap` files in Wireshark. Hand-maintaining Lua dissectors whenever the
//! telemetry database changes is tedious and error-prone; this module compiles the XTCE
//! container hierarchy, restriction criteria, bit offsets, enumerations, and polynomial
//! calibrators directly into a standalone Wireshark Lua script.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::Path;

use xtce_codegen::{
    Calibration, CodegenError, ContainerPlan, Criterion, Field, Guard, GuardTest, Node, Plan, Repr,
};
use xtce_model::{CompareOp, IntegerCoding, XtceDb};

/// Configuration for `xtce wireshark`.
pub struct Options<'a> {
    pub definition: &'a Path,
    pub root: Option<&'a str>,
    pub out: Option<&'a Path>,
    pub udp_port: Option<u16>,
}

/// Compiles `db` into a Wireshark Lua dissector script.
///
/// # Errors
///
/// Returns [`CodegenError`] if the root container cannot be resolved or if the definition uses
/// constructs outside the compilable subset.
pub fn generate_lua(
    db: &XtceDb,
    root: Option<&str>,
    source_label: &str,
    udp_port: Option<u16>,
) -> Result<String, CodegenError> {
    let plan = xtce_codegen::plan(
        db,
        &xtce_codegen::Options {
            root: root.map(str::to_owned),
            source_label: Some(source_label.to_owned()),
        },
    )?;

    Ok(emit_lua(&plan, source_label, udp_port))
}

fn emit_lua(plan: &Plan, source_label: &str, udp_port: Option<u16>) -> String {
    let mut out = String::with_capacity(8192);
    let proto_name = sanitise_proto_name(&plan.root_name);

    emit_header(&mut out, source_label, &plan.root_name, &proto_name);
    emit_proto_fields(&mut out, plan, &proto_name);
    emit_bit_helpers(&mut out);
    emit_container_dissectors(&mut out, &plan.containers);
    emit_dispatcher(&mut out, &plan.root, &plan.containers);
    emit_registration(&mut out, &proto_name, udp_port);

    out
}

fn emit_header(out: &mut String, source_label: &str, root_name: &str, proto_name: &str) {
    let _ = writeln!(
        out,
        "-- Generated by `xtce wireshark` from {source_label} (root: {root_name})."
    );
    let _ = writeln!(
        out,
        "-- Do not edit by hand; regenerate from the XTCE definition."
    );
    let _ = writeln!(out, "--");
    let _ = writeln!(out, "-- Quick start:");
    let _ = writeln!(out, "--   xtce pcap telemetry.bin -o telemetry.pcap");
    let _ = writeln!(
        out,
        "--   wireshark -X lua_script:{proto_name}.lua telemetry.pcap\n"
    );
    let _ = write!(out, "local proto = Proto(\"{proto_name}\", ");
    write_lua_quoted(out, root_name);
    let _ = writeln!(out, ")\n");
}

fn emit_proto_fields(out: &mut String, plan: &Plan, proto_name: &str) {
    let _ = writeln!(
        out,
        "local f__container = ProtoField.string(\"{proto_name}.container\", \"Container\")"
    );

    let mut seen: BTreeSet<&str> = BTreeSet::new();
    let mut field_vars: Vec<(&str, bool)> = Vec::new();

    for container in &plan.containers {
        for field in &container.fields {
            if !seen.insert(field.ident.as_str()) {
                continue;
            }
            let kind = lua_proto_field_kind(&field.repr);
            let _ = write!(
                out,
                "local f_{} = ProtoField.{kind}(\"{proto_name}.{}\", ",
                field.ident, field.ident
            );
            write_lua_quoted(out, &field.xtce_name);
            if matches!(field.repr, Repr::Unsigned | Repr::Signed(_)) {
                let _ = writeln!(out, ", base.DEC)");
            } else {
                let _ = writeln!(out, ")");
            }

            let has_eng = field.calibration.is_some();
            if has_eng {
                let _ = write!(
                    out,
                    "local f_{}_eng = ProtoField.double(\"{proto_name}.{}.eng\", ",
                    field.ident, field.ident
                );
                write_lua_quoted(out, &field.xtce_name);
                let _ = writeln!(out, ")");
            }
            field_vars.push((field.ident.as_str(), has_eng));
        }
    }

    let _ = writeln!(out, "\nproto.fields = {{");
    let _ = writeln!(out, "    f__container,");
    for (ident, has_eng) in &field_vars {
        let _ = writeln!(out, "    f_{ident},");
        if *has_eng {
            let _ = writeln!(out, "    f_{ident}_eng,");
        }
    }
    let _ = writeln!(out, "}}\n");
}

const fn lua_proto_field_kind(repr: &Repr) -> &'static str {
    match repr {
        Repr::Unsigned => "uint64",
        Repr::Signed(_) => "int64",
        Repr::Float16 | Repr::Float32 | Repr::Float64 | Repr::Mil1750a => "double",
        Repr::Bool => "bool",
        Repr::Enumerated(_) | Repr::Text { .. } => "string",
        Repr::Binary => "bytes",
    }
}

fn emit_bit_helpers(out: &mut String) {
    out.push_str(
        r"local function has_bits(tvbuf, bit_offset, bit_width)
    return (bit_offset + bit_width) <= (tvbuf:len() * 8)
end

local function byte_range(tvbuf, bit_offset, bit_width)
    if bit_width == 0 then
        return tvbuf:range(0, 0)
    end
    local start_byte = math.floor(bit_offset / 8)
    local end_byte = math.floor((bit_offset + bit_width - 1) / 8)
    return tvbuf:range(start_byte, end_byte - start_byte + 1)
end

local function read_bits_uint(tvbuf, bit_offset, bit_width, swap_bytes)
    local acc = 0
    for i = 0, bit_width - 1 do
        local pos = bit_offset + i
        local byte_idx = math.floor(pos / 8)
        local bit_idx = 7 - (pos % 8)
        local b = tvbuf:range(byte_idx, 1):uint()
        local bit_val = math.floor(b / (2 ^ bit_idx)) % 2
        acc = acc * 2 + bit_val
    end
    if swap_bytes and bit_width >= 16 and (bit_width % 8 == 0) then
        local nbytes = bit_width / 8
        local swapped = 0
        for _ = 1, nbytes do
            swapped = swapped * 256 + (acc % 256)
            acc = math.floor(acc / 256)
        end
        return swapped
    end
    return acc
end

local function read_bits_int(tvbuf, bit_offset, bit_width, swap_bytes)
    local raw = read_bits_uint(tvbuf, bit_offset, bit_width, swap_bytes)
    local sign_bit = 2 ^ (bit_width - 1)
    if raw >= sign_bit then
        return raw - (2 ^ bit_width)
    end
    return raw
end

",
    );
}

fn emit_container_dissectors(out: &mut String, containers: &[ContainerPlan]) {
    for container in containers {
        let _ = writeln!(
            out,
            "local function dissect_{}(tvbuf, pinfo, subtree)",
            container.type_ident
        );
        let _ = write!(out, "    pinfo.cols.info:set(");
        write_lua_quoted(out, &container.xtce_name);
        let _ = writeln!(out, ")");
        let _ = write!(
            out,
            "    subtree:add(f__container, tvbuf:range(0, tvbuf:len()), "
        );
        write_lua_quoted(out, &container.xtce_name);
        let _ = writeln!(out, ")");

        for field in &container.fields {
            emit_field_dissection(out, field);
        }

        let _ = writeln!(out, "end\n");
    }
}

fn emit_field_dissection(out: &mut String, field: &Field) {
    let Some((bit_offset, bit_width)) = field.static_span() else {
        return;
    };
    if bit_width == 0 {
        return;
    }

    let swap = if field.swap_bytes { "true" } else { "false" };
    let ident = &field.ident;
    let _ = writeln!(
        out,
        "    if has_bits(tvbuf, {bit_offset}, {bit_width}) then"
    );
    let _ = writeln!(
        out,
        "        local rng = byte_range(tvbuf, {bit_offset}, {bit_width})"
    );

    match &field.repr {
        Repr::Unsigned => {
            let _ = writeln!(
                out,
                "        local raw = read_bits_uint(tvbuf, {bit_offset}, {bit_width}, {swap})"
            );
            let _ = writeln!(out, "        subtree:add(f_{ident}, rng, UInt64.new(raw))");
            emit_calibration(out, field);
        }
        Repr::Signed(IntegerCoding::TwosComplement) => {
            let _ = writeln!(
                out,
                "        local raw = read_bits_int(tvbuf, {bit_offset}, {bit_width}, {swap})"
            );
            let _ = writeln!(out, "        subtree:add(f_{ident}, rng, Int64.new(raw))");
            emit_calibration(out, field);
        }
        Repr::Signed(_) => {
            let _ = writeln!(
                out,
                "        local raw = read_bits_uint(tvbuf, {bit_offset}, {bit_width}, {swap})"
            );
            let _ = writeln!(out, "        subtree:add(f_{ident}, rng, Int64.new(raw))");
            emit_calibration(out, field);
        }
        Repr::Bool => {
            let _ = writeln!(
                out,
                "        local raw = read_bits_uint(tvbuf, {bit_offset}, {bit_width}, {swap})"
            );
            let _ = writeln!(out, "        subtree:add(f_{ident}, rng, raw ~= 0)");
        }
        Repr::Enumerated(entries) => {
            let _ = writeln!(
                out,
                "        local raw = read_bits_int(tvbuf, {bit_offset}, {bit_width}, {swap})"
            );
            let _ = writeln!(out, "        local label = tostring(raw)");
            for (low, high, label) in entries {
                if low == high {
                    let _ = write!(out, "        if raw == {low} then label = ");
                } else {
                    let _ = write!(
                        out,
                        "        if raw >= {low} and raw <= {high} then label = "
                    );
                }
                write_lua_quoted(out, label);
                let _ = writeln!(out, " .. \" (\" .. tostring(raw) .. \")\" end");
            }
            let _ = writeln!(out, "        subtree:add(f_{ident}, rng, label)");
        }
        Repr::Float32 | Repr::Float64 if bit_offset % 8 == 0 && !field.swap_bytes => {
            let _ = writeln!(out, "        local raw = rng:float()");
            let _ = writeln!(out, "        subtree:add(f_{ident}, rng, raw)");
            emit_calibration(out, field);
        }
        Repr::Float16 | Repr::Float32 | Repr::Float64 | Repr::Mil1750a => {
            let _ = writeln!(
                out,
                "        local raw = read_bits_uint(tvbuf, {bit_offset}, {bit_width}, {swap})"
            );
            let _ = writeln!(out, "        subtree:add(f_{ident}, rng, raw)");
            emit_calibration(out, field);
        }
        Repr::Text { .. } => {
            let _ = writeln!(out, "        subtree:add(f_{ident}, rng, rng:string())");
        }
        Repr::Binary => {
            let _ = writeln!(out, "        subtree:add(f_{ident}, rng)");
        }
    }

    let _ = writeln!(out, "    end");
}

fn emit_calibration(out: &mut String, field: &Field) {
    let Some(Calibration::Polynomial(terms)) = &field.calibration else {
        return;
    };
    if terms.is_empty() {
        return;
    }
    let _ = write!(out, "        local eng = 0.0");
    for term in terms {
        let c = term.coefficient;
        let e = term.exponent;
        let _ = write!(out, " + ({c:?} * (raw ^ {e}))");
    }
    let _ = writeln!(out);
    let _ = writeln!(out, "        subtree:add(f_{}_eng, rng, eng)", field.ident);
}

fn emit_dispatcher(out: &mut String, root: &Node, containers: &[ContainerPlan]) {
    let _ = writeln!(out, "local function dispatch(tvbuf, pinfo, subtree)");
    emit_node_dispatch(out, root, containers, 1);
    let _ = writeln!(out, "    return false");
    let _ = writeln!(out, "end\n");
}

fn emit_node_dispatch(out: &mut String, node: &Node, containers: &[ContainerPlan], depth: usize) {
    for (criterion, child) in &node.children {
        write_indent(out, depth);
        let _ = write!(out, "if ");
        emit_criterion_expr(out, criterion);
        let _ = writeln!(out, " then");
        emit_node_dispatch(out, child, containers, depth + 1);
        write_indent(out, depth);
        let _ = writeln!(out, "end");
    }

    if !node.is_abstract {
        if let Some(idx) = node.plan {
            if let Some(plan) = containers.get(idx) {
                write_indent(out, depth);
                let _ = writeln!(out, "dissect_{}(tvbuf, pinfo, subtree)", plan.type_ident);
                write_indent(out, depth);
                let _ = writeln!(out, "return true");
            }
        }
    }
}

fn emit_criterion_expr(out: &mut String, criterion: &Criterion) {
    match criterion {
        Criterion::Test(guard) => emit_guard_expr(out, guard),
        Criterion::All(children) => {
            if children.is_empty() {
                out.push_str("true");
                return;
            }
            out.push('(');
            for (idx, child) in children.iter().enumerate() {
                if idx > 0 {
                    out.push_str(" and ");
                }
                emit_criterion_expr(out, child);
            }
            out.push(')');
        }
        Criterion::Any(children) => {
            if children.is_empty() {
                out.push_str("false");
                return;
            }
            out.push('(');
            for (idx, child) in children.iter().enumerate() {
                if idx > 0 {
                    out.push_str(" or ");
                }
                emit_criterion_expr(out, child);
            }
            out.push(')');
        }
    }
}

fn emit_guard_expr(out: &mut String, guard: &Guard) {
    let offset = guard.bit_offset;
    let width = guard.bit_width;
    let swap = if guard.swap_bytes { "true" } else { "false" };
    let reader = if matches!(guard.repr, Repr::Signed(_)) {
        "read_bits_int"
    } else {
        "read_bits_uint"
    };

    let _ = write!(out, "(has_bits(tvbuf, {offset}, {width}) and ");
    match &guard.test {
        GuardTest::Value { operator, value } => {
            let op = lua_compare_op(*operator);
            let _ = write!(
                out,
                "({reader}(tvbuf, {offset}, {width}, {swap}) {op} {value}))"
            );
        }
        GuardTest::Labels { ranges, .. } => {
            if ranges.is_empty() {
                out.push_str("false)");
                return;
            }
            out.push('(');
            for (idx, (low, high)) in ranges.iter().enumerate() {
                if idx > 0 {
                    out.push_str(" or ");
                }
                if low == high {
                    let _ = write!(out, "({reader}(tvbuf, {offset}, {width}, {swap}) == {low})");
                } else {
                    let _ = write!(
                        out,
                        "({reader}(tvbuf, {offset}, {width}, {swap}) >= {low} and \
                         {reader}(tvbuf, {offset}, {width}, {swap}) <= {high})"
                    );
                }
            }
            out.push_str("))");
        }
    }
}

const fn lua_compare_op(op: CompareOp) -> &'static str {
    match op {
        CompareOp::Equal => "==",
        CompareOp::NotEqual => "~=",
        CompareOp::Less => "<",
        CompareOp::LessOrEqual => "<=",
        CompareOp::Greater => ">",
        CompareOp::GreaterOrEqual => ">=",
    }
}

fn emit_registration(out: &mut String, proto_name: &str, udp_port: Option<u16>) {
    let _ = writeln!(
        out,
        "function proto.dissector(tvbuf, pinfo, root)\n    \
         pinfo.cols.protocol:set(\"{proto_name}\")\n    \
         local subtree = root:add(proto, tvbuf:range(0, tvbuf:len()))\n    \
         if not dispatch(tvbuf, pinfo, subtree) then\n        \
         pinfo.cols.info:set(\"Unrecognised XTCE packet\")\n    \
         end\n\
         end\n"
    );

    let _ = writeln!(
        out,
        "local wtap_table = DissectorTable.get(\"wtap_encap\")\n\
         if wtap_table and wtap_encaps and wtap_encaps.USER0 then\n    \
         wtap_table:add(wtap_encaps.USER0, proto)\n\
         end"
    );

    if let Some(port) = udp_port {
        let _ = writeln!(
            out,
            "\nlocal udp_table = DissectorTable.get(\"udp.port\")\n\
             if udp_table then\n    \
             udp_table:add({port}, proto)\n\
             end"
        );
    }
}

fn write_indent(out: &mut String, depth: usize) {
    for _ in 0..depth {
        out.push_str("    ");
    }
}

fn sanitise_proto_name(name: &str) -> String {
    let mut out = String::with_capacity(5 + name.len());
    out.push_str("xtce_");
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push('_');
        }
    }
    out
}

fn write_lua_quoted(out: &mut String, text: &str) {
    out.push('"');
    for ch in text.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            c if c.is_control() => {
                let _ = write!(out, "\\{:03}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
}

/// Executes `xtce wireshark` using a pre-loaded [`XtceDb`].
///
/// # Errors
///
/// Returns an error if dissector compilation or file output fails.
pub fn run_with_db(db: &XtceDb, options: &Options<'_>) -> Result<(), Box<dyn std::error::Error>> {
    let label = if options.definition.as_os_str() == "-" {
        "<stdin>"
    } else {
        options.definition.to_str().unwrap_or("<definition>")
    };
    let lua = generate_lua(db, options.root, label, options.udp_port)?;

    match options.out {
        Some(path) if path.as_os_str() != "-" => {
            std::fs::write(path, lua)?;
            eprintln!("wrote Wireshark dissector to {}", path.display());
        }
        _ => print!("{lua}"),
    }

    Ok(())
}

#[cfg(test)]
mod tests {
    use xtce_model::XtceDb;

    use super::{generate_lua, write_lua_quoted};

    const SAMPLE_XTCE: &str = r#"<?xml version="1.0" encoding="UTF-8"?>
<xtce:SpaceSystem name="CubeSat" xmlns:xtce="http://www.omg.org/spec/XTCE/20180204">
  <xtce:TelemetryMetaData>
    <xtce:ParameterTypeSet>
      <xtce:IntegerParameterType name="APID_T" signed="false">
        <xtce:IntegerDataEncoding sizeInBits="11" encoding="unsigned"/>
      </xtce:IntegerParameterType>
      <xtce:EnumeratedParameterType name="MODE_T">
        <xtce:IntegerDataEncoding sizeInBits="5" encoding="unsigned"/>
        <xtce:EnumerationList>
          <xtce:Enumeration value="0" label="SAFE"/>
          <xtce:Enumeration value="1" label="NOMINAL"/>
        </xtce:EnumerationList>
      </xtce:EnumeratedParameterType>
      <xtce:IntegerParameterType name="TEMP_T" signed="true">
        <xtce:IntegerDataEncoding sizeInBits="16" encoding="twosComplement">
          <xtce:DefaultCalibrator>
            <xtce:PolynomialCalibrator>
              <xtce:Term exponent="0" coefficient="-40.0"/>
              <xtce:Term exponent="1" coefficient="0.01"/>
            </xtce:PolynomialCalibrator>
          </xtce:DefaultCalibrator>
        </xtce:IntegerDataEncoding>
      </xtce:IntegerParameterType>
    </xtce:ParameterTypeSet>
    <xtce:ParameterSet>
      <xtce:Parameter name="APID" parameterTypeRef="APID_T"/>
      <xtce:Parameter name="MODE" parameterTypeRef="MODE_T"/>
      <xtce:Parameter name="TEMP" parameterTypeRef="TEMP_T"/>
    </xtce:ParameterSet>
    <xtce:ContainerSet>
      <xtce:SequenceContainer name="CCSDSPacket" abstract="true">
        <xtce:EntryList>
          <xtce:ParameterRefEntry parameterRef="APID"/>
          <xtce:ParameterRefEntry parameterRef="MODE"/>
        </xtce:EntryList>
      </xtce:SequenceContainer>
      <xtce:SequenceContainer name="HkPacket">
        <xtce:BaseContainer containerRef="CCSDSPacket">
          <xtce:RestrictionCriteria>
            <xtce:Comparison parameterRef="APID" value="42"/>
          </xtce:RestrictionCriteria>
        </xtce:BaseContainer>
        <xtce:EntryList>
          <xtce:ParameterRefEntry parameterRef="TEMP"/>
        </xtce:EntryList>
      </xtce:SequenceContainer>
    </xtce:ContainerSet>
  </xtce:TelemetryMetaData>
</xtce:SpaceSystem>"#;

    #[test]
    fn generates_lua_dissector_with_proto_fields_and_containers() {
        let db = XtceDb::from_xml(SAMPLE_XTCE).expect("valid xml");
        let lua = generate_lua(&db, None, "cubesat.xml", Some(5005)).expect("generates lua");

        assert!(lua.contains("local proto = Proto(\"xtce_ccsdspacket\", \"CCSDSPacket\")"));
        assert!(lua.contains("ProtoField.uint64(\"xtce_ccsdspacket.apid\", \"APID\", base.DEC)"));
        assert!(lua.contains("ProtoField.string(\"xtce_ccsdspacket.mode\", \"MODE\")"));
        assert!(lua.contains("ProtoField.int64(\"xtce_ccsdspacket.temp\", \"TEMP\", base.DEC)"));
        assert!(lua.contains("ProtoField.double(\"xtce_ccsdspacket.temp.eng\", \"TEMP\")"));
        assert!(lua.contains("local function dissect_Hkpacket(tvbuf, pinfo, subtree)"));
        assert!(lua.contains("(read_bits_uint(tvbuf, 0, 11, false) == 42)"));
        assert!(lua.contains("if raw == 0 then label = \"SAFE\""));
        assert!(lua.contains("if raw == 1 then label = \"NOMINAL\""));
        assert!(lua.contains("wtap_table:add(wtap_encaps.USER0, proto)"));
        assert!(lua.contains("udp_table:add(5005, proto)"));
    }

    #[test]
    fn omits_udp_registration_when_port_is_none() {
        let db = XtceDb::from_xml(SAMPLE_XTCE).expect("valid xml");
        let lua = generate_lua(&db, None, "cubesat.xml", None).expect("generates lua");

        assert!(lua.contains("wtap_table:add(wtap_encaps.USER0, proto)"));
        assert!(!lua.contains("udp_table:add("));
    }

    #[test]
    fn escapes_lua_strings_safely() {
        let mut buf = String::new();
        write_lua_quoted(&mut buf, "a\"b\\c\nd");
        assert_eq!(buf, "\"a\\\"b\\\\c\\nd\"");
    }
}
